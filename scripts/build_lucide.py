"""Write the dashboard's Lucide subset: src/job_match/dashboard/assets/lucide.js.

Lucide (ISC, see assets/LICENSES.md) ships its icons as "icon nodes" ([tag, attrs] pairs); the
page builds them with createElementNS, so no SVG markup is ever parsed (the dashboard has no
innerHTML). Only the icons the page names are kept. Run it once by hand after adding a name:

    npm pack lucide-static@1.61.0 --pack-destination <dir>   # then extract the tarball
    python scripts/build_lucide.py <dir>/package/icon-nodes.json

Development only: the build and the daily run never fetch anything.
"""
from __future__ import annotations

import json
import sys
from pathlib import Path

OUT = Path(__file__).resolve().parents[1] / "src/job_match/dashboard/assets/lucide.js"
NAMES = """layers briefcase-business list radar activity search x check undo-2 external-link
calendar calendar-clock file-text chevron-down chevron-right keyboard kanban rows-3 map-pin clock
building circle-dot arrow-left arrow-right corner-down-left circle-check circle-x loader-circle
timer sliders-horizontal banknote users newspaper rotate-ccw triangle-alert wifi-off refresh-cw
quote plus info git-branch link notebook-pen""".split()

FOOTER = '''  };
  var NS = "http://www.w3.org/2000/svg";
  /* An <svg> for `name`, hidden from assistive tech (the control next to it carries the words). */
  function icon(name, cls) {
    var parts = NODES[name];
    if (!parts) throw new Error("unknown icon: " + name);
    var svg = document.createElementNS(NS, "svg");
    var attrs = {
      class: "i" + (cls ? " " + cls : ""), width: "16", height: "16", viewBox: "0 0 24 24",
      fill: "none", stroke: "currentColor", "stroke-width": "1.5", "stroke-linecap": "round",
      "stroke-linejoin": "round", "aria-hidden": "true", focusable: "false"
    };
    Object.keys(attrs).forEach(function (k) { svg.setAttribute(k, attrs[k]); });
    parts.forEach(function (p) {
      var child = document.createElementNS(NS, p[0]);
      Object.keys(p[1]).forEach(function (k) { child.setAttribute(k, p[1][k]); });
      svg.appendChild(child);
    });
    return svg;
  }
  var api = { icon: icon, names: Object.keys(NODES) };
  if (typeof module !== "undefined" && module.exports) module.exports = api;
  else root.JMIcons = api;
})(this);
'''


def main(nodes_path: str) -> None:
    nodes = json.loads(Path(nodes_path).read_text(encoding="utf-8"))
    missing = [n for n in NAMES if n not in nodes]
    if missing:
        sys.exit("unknown in this Lucide version: " + ", ".join(missing))
    lines = [
        "/* Lucide icons (lucide-static 1.61.0, ISC licence, see LICENSES.md): the dashboard's",
        "   subset as icon nodes, built with createElementNS. 16 px, stroke 1.5. Generated by",
        "   scripts/build_lucide.py; do not edit by hand. */",
        "(function (root) {",
        '  "use strict";',
        "  var NODES = {",
    ]
    entries = [f"    {json.dumps(n)}: {json.dumps(nodes[n], separators=(',', ':'))}" for n in NAMES]
    lines.append(",\n".join(entries))
    OUT.write_text("\n".join(lines) + "\n" + FOOTER, encoding="utf-8", newline="\n")
    print(f"{len(NAMES)} icons -> {OUT}")


if __name__ == "__main__":
    if len(sys.argv) != 2:
        sys.exit(__doc__)
    main(sys.argv[1])
